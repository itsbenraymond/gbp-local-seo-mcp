#!/usr/bin/env node
// Generates src/benchmarks.js from our own Google Maps scrape.
//
//   node tools/build-benchmarks.mjs
//
// This is the thing nobody else has: real Australian numbers, per Google
// primary category, for review count, star rating and name compliance. Every
// other local SEO tool quotes American survey data from years ago.
//
// Two tables come out of it:
//   CATEGORIES  per Google primary category: percentiles + name compliance
//   TRADE_MAP   plain-English trade words -> the Google categories real
//               businesses in that trade actually use, with counts
//
// Only categories with at least MIN_N businesses ship. A percentile off eight
// businesses is a number with no information in it, and publishing it would be
// exactly the kind of made-up benchmark this is meant to replace.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const pkg = path.resolve(here, '..');
const repo = path.resolve(pkg, '../../../../..');
const DUMP = path.join(repo, '.build/leads-dump.json');
const MIN_N = 20;

const { checkBusinessName } = await import(pathToFileURL(path.join(pkg, 'src/text-checks.js')).href);

const raw = JSON.parse(fs.readFileSync(DUMP, 'utf8'));
const hdr = raw[0];
const ix = (n) => hdr.indexOf(n);

const seen = new Set();
const rows = [];
for (const r of raw.slice(1)) {
  const name = String(r[ix('business')] || '').trim();
  const category = String(r[ix('category')] || '').trim();
  if (!name || !category) continue;
  const key = name.toLowerCase();
  if (seen.has(key)) continue;
  seen.add(key);
  const area = String(r[ix('area')] || '').trim();
  rows.push({
    name, category, area,
    trade: String(r[ix('industry')] || '').trim().toLowerCase(),
    rating: Number.parseFloat(r[ix('rating')]),
    reviews: Number.parseInt(String(r[ix('review_count')]).replace(/[^\d]/g, ''), 10),
    verdict: checkBusinessName({ name, city: area }).verdict,
  });
}

const pctl = (sorted, p) => sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * p))];
const round1 = (n) => Number(n.toFixed(1));

// --- per-category benchmarks --------------------------------------------
const grouped = {};
for (const r of rows) (grouped[r.category] ||= []).push(r);

const CATEGORIES = {};
for (const [cat, list] of Object.entries(grouped)) {
  if (list.length < MIN_N) continue;
  const revs = list.map((r) => r.reviews).filter(Number.isFinite).sort((a, b) => a - b);
  const rats = list.map((r) => r.rating).filter((n) => Number.isFinite(n) && n > 0).sort((a, b) => a - b);
  if (revs.length < MIN_N) continue;
  CATEGORIES[cat.toLowerCase()] = {
    label: cat,
    n: list.length,
    reviews: { p10: pctl(revs, 0.1), p25: pctl(revs, 0.25), p50: pctl(revs, 0.5), p75: pctl(revs, 0.75), p90: pctl(revs, 0.9) },
    rating: rats.length
      ? { p10: round1(pctl(rats, 0.1)), p25: round1(pctl(rats, 0.25)), p50: round1(pctl(rats, 0.5)), p75: round1(pctl(rats, 0.75)), p90: round1(pctl(rats, 0.9)) }
      : null,
    nameNotCleanPct: round1((list.filter((r) => r.verdict !== 'PASS').length / list.length) * 100),
  };
}

// --- trade words -> the categories real businesses use -------------------
const tradeRaw = {};
for (const r of rows) {
  if (!r.trade) continue;
  ((tradeRaw[r.trade] ||= {})[r.category] ||= 0);
  tradeRaw[r.trade][r.category]++;
}
const TRADE_MAP = {};
for (const [trade, cats] of Object.entries(tradeRaw)) {
  const total = Object.values(cats).reduce((a, b) => a + b, 0);
  if (total < 5) continue;
  TRADE_MAP[trade] = {
    n: total,
    categories: Object.entries(cats)
      .sort((a, b) => b[1] - a[1])
      .slice(0, 6)
      .map(([label, n]) => ({ label, n, pct: round1((n / total) * 100) })),
  };
}

// --- the whole-sample line ----------------------------------------------
const allRevs = rows.map((r) => r.reviews).filter(Number.isFinite).sort((a, b) => a - b);
const allRats = rows.map((r) => r.rating).filter((n) => Number.isFinite(n) && n > 0).sort((a, b) => a - b);
const OVERALL = {
  n: rows.length,
  suburbs: new Set(rows.map((r) => r.area).filter(Boolean)).size,
  categories: Object.keys(grouped).length,
  reviews: { p25: pctl(allRevs, 0.25), p50: pctl(allRevs, 0.5), p75: pctl(allRevs, 0.75), p90: pctl(allRevs, 0.9) },
  rating: { p25: round1(pctl(allRats, 0.25)), p50: round1(pctl(allRats, 0.5)), p75: round1(pctl(allRats, 0.75)) },
  nameNotCleanPct: round1((rows.filter((r) => r.verdict !== 'PASS').length / rows.length) * 100),
};

const out = `// GENERATED by tools/build-benchmarks.mjs. Do not hand-edit.
// Source: Kangaroo Growth's own Google Maps scrape of Australian local
// businesses. Convenience sample, metro-skewed, leans to the trades and
// service categories we sell to. Published in full at
// https://kangaroogrowth.com.au/research/google-business-profile-names-australia
export const GENERATED = ${JSON.stringify(new Date().toISOString().slice(0, 10))};
export const MIN_SAMPLE = ${MIN_N};
export const OVERALL = ${JSON.stringify(OVERALL)};
export const CATEGORIES = ${JSON.stringify(CATEGORIES)};
export const TRADE_MAP = ${JSON.stringify(TRADE_MAP)};
`;

const dest = path.join(pkg, 'src/benchmarks.js');
fs.writeFileSync(dest, out);
console.log(`${rows.length} businesses · ${Object.keys(CATEGORIES).length} categories at n>=${MIN_N} · ${Object.keys(TRADE_MAP).length} trade terms`);
console.log(`wrote src/benchmarks.js (${(out.length / 1024).toFixed(1)}KB)`);
